export { kebabToCamel } from "../naming.js";

/**
 * True when `name` can be used as an agent name: kebab-case, and not a word
 * that would make the exported function unparseable.
 */
export function validateAgentName(name: string): boolean {
  return agentNameProblem(name) === undefined;
}

/** True when the project in `dir` lists `name` among its dependencies. */
function projectHasDependency(dir: string, name: string): boolean {
  try {
    const manifest = JSON.parse(
      readFileSync(join(dir, "package.json"), "utf-8"),
    ) as Record<string, Record<string, string> | undefined>;
    return Boolean(
      manifest.dependencies?.[name] ?? manifest.devDependencies?.[name],
    );
  } catch {
    // No readable package.json: nothing here can run a test file.
    return false;
  }
}

/**
 * Generate YAML content for an agent
 */
export function generateAgentYaml(
  name: string,
  options: {
    type: AgentType | "custom";
    model: string;
    tools?: string[];
  },
): string {
  const vars: TemplateVars = {
    name,
    model: options.model,
    agentName: kebabToCamel(name),
  };

  // Custom type uses general template with minimal config
  const templateType =
    options.type === "custom" ? "general" : (options.type as AgentType);

  // Load base template
  let content = loadAgentTemplate(templateType, vars);

  // For custom type, strip most of the template to minimal
  if (options.type === "custom") {
    // The model id goes into the YAML inside double quotes, so it must be
    // well-formed: the shape check rules out the quotes and newlines that
    // would end the string early.
    const safeModel: string = isModelId(options.model)
      ? options.model
      : DEFAULT_MODEL;

    content = `# Custom agent - minimal template
# Created with: symplek add agent ${name} --type custom

name: ${name}
version: "1.0.0"

model: "${safeModel}"

systemPrompt: |
  You are ${name}, a helpful AI assistant.
  Customize this prompt for your specific use case.

temperature: 0.7
maxTokens: 2048
`;
  }

  // Add custom tools if provided and different from template defaults
  if (options.tools && options.tools.length > 0 && options.type === "custom") {
    content += `
tools:
${options.tools.map((tool) => `  - name: ${tool}`).join("\n")}
`;
  }

  return content;
}

/**
 * Generate TypeScript content for an agent
 */
export function generateAgentTypeScript(
  name: string,
  options: {
    model: string;
    tools?: string[];
  },
): string {
  const vars: TemplateVars = {
    name,
    model: options.model,
    agentName: kebabToCamel(name),
  };

  return loadAgentTemplate("typescript", vars);
}

/**
 * Generate test file content for an agent
 */
export function generateAgentTest(name: string): string {
  const agentName = kebabToCamel(name);

  return `/**
 * Tests for the ${name} agent
 * Generated by: symplek add agent ${name}
 */
import { createContext } from "@symplek/core";
import { beforeEach, describe, expect, it, vi } from "vitest";

// Only the model call is replaced, so these tests need no API key and make no
// network request. The agent under test is the real one in ../agents/${name}.
const { ai } = vi.hoisted(() => ({ ai: vi.fn() }));
vi.mock("@symplek/core/server", async (importOriginal) => ({
  ...(await importOriginal<typeof import("@symplek/core/server")>()),
  ai,
}));

import { ${agentName} } from "../agents/${name}";

describe("${name} agent", () => {
  beforeEach(() => {
    ai.mockReset();
  });

  it("does nothing until it is run", () => {
    ${agentName}("Hello");
    expect(ai).not.toHaveBeenCalled();
  });

  it("sends the prompt to the model and returns the reply", async () => {
    ai.mockResolvedValue("a reply");

    const result = await ${agentName}("Hello").run(createContext());

    expect(result.value).toBe("a reply");
    expect(ai).toHaveBeenCalledTimes(1);
    expect(ai.mock.calls[0][0]).toBe("Hello");
  });

  it("surfaces a model failure instead of swallowing it", async () => {
    ai.mockRejectedValue(new Error("provider unavailable"));

    await expect(${agentName}("Hello").run(createContext())).rejects.toThrow();
  });
});
`;
}

interface AgentPromptAnswers {
  type: AgentType | "custom";
  model: string;
  tools: string[];
  createTest: boolean;
}

interface OverwriteAnswers {
  overwrite: boolean;
}

/**
 * Prompt user for agent configuration
 */
async function promptAgentConfig(): Promise<AgentPromptAnswers> {
  const answers = await inquirer.prompt<AgentPromptAnswers>([
    {
      type: "list",
      name: "type",
      message: "Select agent type:",
      choices: Object.entries(AGENT_TYPES).map(
        ([value, { name, description }]) => ({
          name: `${name} - ${description}`,
          value,
        }),
      ),
      default: "general",
    },
    {
      type: "list",
      name: "model",
      message: "Select AI model:",
      choices: SUGGESTED_MODELS.map((model) => ({ name: model, value: model })),
      default: DEFAULT_MODEL,
    },
    {
      type: "checkbox",
      name: "tools",
      message: "Select tools (optional):",
      choices: AVAILABLE_TOOLS.map((tool) => ({
        name: `${tool.name} - ${tool.description}`,
        value: tool.value,
      })),
    },
    {
      type: "confirm",
      name: "createTest",
      message: "Create test file?",
      default: true,
    },
  ]);

  return answers;
}

/**
 * Prompt for overwrite confirmation
 */
async function promptOverwrite(filePath: string): Promise<boolean> {
  const { overwrite } = await inquirer.prompt<OverwriteAnswers>([
    {
      type: "confirm",
      name: "overwrite",
      message: `File ${filePath} already exists. Overwrite?`,
      default: false,
    },
  ]);
  return overwrite;
}

/**
 * Write file with directory creation
 */
function writeFile(filePath: string, content: string): void {
  const dir = dirname(filePath);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
  writeFileSync(filePath, content, "utf-8");
}

/**
 * Create the add command with subcommands
 */
export function createAddCommand(): Command {
  const addCommand = new Command("add").description(
    "Add new components to your project",
  );

  // symplek add agent <name>
  addCommand
    .command("agent <name>")
    .description("Scaffold a new AI agent")
    .option("--yaml-only", "Only create YAML definition file")
    .option("--ts-only", "Only create TypeScript implementation file")
    .option(
      "-t, --type <type>",
      "Agent type (general, researcher, reviewer, typescript, custom)",
    )
    .option("-m, --model <model>", "AI model to use")
    .option("--no-test", "Skip test file creation")
    .action(
      async (
        name: string,
        options: {
          yamlOnly?: boolean;
          tsOnly?: boolean;
          type?: string;
          model?: string;
          test?: boolean;
        },
      ) => {
        // Validate the name: kebab-case, and usable as a function name.
        const nameProblem = agentNameProblem(name);
        if (nameProblem) {
          console.error(chalk.red(`Error: ${nameProblem}`));
          console.error(chalk.gray(`  Got: "${name}"`));
          console.error(
            chalk.gray(
              `  Valid examples: research-agent, code-reviewer, my-bot`,
            ),
          );
          process.exit(1);
        }

        // Determine file paths
        const cwd = process.cwd();
        const yamlPath = join(cwd, "agents", `${name}.yaml`);
        const tsPath = join(cwd, "agents", `${name}.ts`);
        const testPath = join(cwd, "tests", `${name}.test.ts`);

        // Get configuration - either from options or prompts
        let config: AgentPromptAnswers;

        // An unknown --type would otherwise reach the template loader and
        // fail there with a file-not-found error that names no valid choice.
        if (
          options.type !== undefined &&
          !Object.keys(AGENT_TYPES).includes(options.type)
        ) {
          console.error(chalk.red(`Error: unknown agent type "${options.type}"`));
          console.error(
            chalk.gray(`  Use one of: ${Object.keys(AGENT_TYPES).join(", ")}`),
          );
          process.exit(1);
        }

        if (options.model !== undefined && !isModelId(options.model)) {
          console.error(chalk.red(`Error: invalid model id "${options.model}"`));
          console.error(chalk.gray(`  ${MODEL_ID_HINT}`));
          process.exit(1);
        }

        if (options.yamlOnly && options.tsOnly) {
          console.error(
            chalk.red("Error: --yaml-only and --ts-only cannot be used together"),
          );
          process.exit(1);
        }

        if (options.type || options.model) {
          // Either flag makes the run non-interactive; the other takes its
          // default. Asking again would throw away what was passed.
          config = {
            type: (options.type ?? "general") as AgentType | "custom",
            model: options.model ?? DEFAULT_MODEL,
            tools: [],
            createTest: options.test !== false,
          };
        } else if (!process.stdin.isTTY) {
          console.error(
            chalk.red("Error: no terminal to ask questions on."),
          );
          console.error(
            chalk.gray(
              `  Pass --type (${Object.keys(AGENT_TYPES).join(", ")}) and optionally --model.`,
            ),
          );
          process.exit(1);
        } else {
          // Interactive mode
          console.log(chalk.blue(`\nCreating agent: ${chalk.bold(name)}\n`));
          config = await promptAgentConfig();
        }

        if (config.type === "typescript" && options.yamlOnly) {
          console.error(
            chalk.red(
              "Error: the typescript agent type has no YAML file, so --yaml-only leaves nothing to create",
            ),
          );
          process.exit(1);
        }

        const filesToCreate: Array<{
          path: string;
          content: string;
          type: string;
        }> = [];

        // Determine which files to create
        // The "typescript" type is a hand-written agent with no YAML source.
        // Writing a YAML file for it put TypeScript into agents/<name>.yaml,
        // which then failed `symplek validate` and `symplek generate`.
        const createYaml = !options.tsOnly && config.type !== "typescript";
        // For a YAML-defined agent the TypeScript is generated from the YAML,
        // by the same code `symplek generate` runs. Writing a separate
        // hand-editable file here meant the next `symplek generate` silently
        // replaced whatever the user had put in it.
        const generateTs = createYaml && !options.yamlOnly;
        // A hand-written TypeScript agent is created only when there is no
        // YAML to generate from: the typescript type, or --ts-only.
        const createTs = !createYaml && !options.yamlOnly;
        // The test needs the TypeScript agent, and a test runner to run it.
        const canRunTests = projectHasDependency(cwd, "vitest");
        const writesTs = generateTs || createTs;
        const createTest = config.createTest && writesTs && canRunTests;

        // Generation refuses to replace a hand-written agent. Find that out
        // before anything is written, so a refusal leaves no files behind.
        if (generateTs && isHandWritten(tsPath)) {
          console.error(
            chalk.red(
              `Error: ${tsPath} already exists and was not generated from YAML. Move or delete it, then run this command again`,
            ),
          );
          process.exit(1);
        }

        // Check for existing files and prepare content
        if (createYaml) {
          if (existsSync(yamlPath)) {
            const shouldOverwrite = await promptOverwrite(yamlPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${yamlPath}`));
            } else {
              filesToCreate.push({
                path: yamlPath,
                content: generateAgentYaml(name, config),
                type: "YAML definition",
              });
            }
          } else {
            filesToCreate.push({
              path: yamlPath,
              content: generateAgentYaml(name, config),
              type: "YAML definition",
            });
          }
        }

        if (createTs) {
          if (existsSync(tsPath)) {
            const shouldOverwrite = await promptOverwrite(tsPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${tsPath}`));
            } else {
              filesToCreate.push({
                path: tsPath,
                content: generateAgentTypeScript(name, config),
                type: "TypeScript implementation",
              });
            }
          } else {
            filesToCreate.push({
              path: tsPath,
              content: generateAgentTypeScript(name, config),
              type: "TypeScript implementation",
            });
          }
        }

        if (createTest) {
          if (existsSync(testPath)) {
            const shouldOverwrite = await promptOverwrite(testPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${testPath}`));
            } else {
              filesToCreate.push({
                path: testPath,
                content: generateAgentTest(name),
                type: "test file",
              });
            }
          } else {
            filesToCreate.push({
              path: testPath,
              content: generateAgentTest(name),
              type: "test file",
            });
          }
        }

        // Create files
        if (filesToCreate.length === 0) {
          console.log(chalk.yellow("\nNo files to create."));
          return;
        }

        const spinner = ora("Creating agent files...").start();

        try {
          const created = filesToCreate.map((file) => ({
            path: file.path,
            type: file.type,
          }));
          for (const file of filesToCreate) {
            writeFile(file.path, file.content);
          }
          if (generateTs) {
            const generated = generateFile(yamlPath, undefined, true);
            if (!generated.success) {
              throw new Error(
                `Could not generate ${tsPath} from ${yamlPath}: ${generated.error}`,
              );
            }
            created.push({ path: tsPath, type: "generated from the YAML" });
          }
          spinner.succeed("Agent files created successfully!");

          // Summary
          console.log(chalk.green("\n✓ Created files:"));
          for (const file of created) {
            console.log(chalk.gray(`  - ${file.path} (${file.type})`));
          }

          // Next steps: only the ones that apply to the files just written.
          const nextSteps: string[] = [];
          if (createYaml) {
            nextSteps.push(`Edit ${yamlPath} to customize your agent`);
          }
          if (generateTs) {
            nextSteps.push(
              `Run "symplek generate" after each edit to refresh ${tsPath}. Do not edit that file by hand`,
            );
          }
          if (createTs) {
            nextSteps.push(`Edit ${tsPath} to customize your agent`);
          }
          nextSteps.push(
            writesTs
              ? `Import ${kebabToCamel(name)} from ${tsPath} and call .run(createContext())`
              : `Run "symplek generate" to write ${tsPath} from the YAML`,
          );
          console.log(chalk.blue("\n📝 Next steps:"));
          nextSteps.forEach((step, index) => {
            console.log(chalk.gray(`  ${index + 1}. ${step}`));
          });
          if (config.createTest && writesTs && !canRunTests) {
            console.log(
              chalk.gray(
                "\n  No test file was written: this project has no vitest. Add it, then run this command again for a test",
              ),
            );
          }
        } catch (error) {
          spinner.fail("Failed to create agent files");
          console.error(
            chalk.red(error instanceof Error ? error.message : String(error)),
          );
          process.exit(1);
        }
      },
    );

  return addCommand;
}
