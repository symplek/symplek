/**
 * `Weft add` command - scaffolds new components
 * Supports: agent (more types coming in future stories)
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import chalk from "chalk";
import { Command } from "commander";
import inquirer from "inquirer";
import ora from "ora";
import {
  type AgentType,
  loadAgentTemplate,
  type TemplateVars,
} from "../utils/templates.js";

/** Available models for agent creation */
const AVAILABLE_MODELS = [
  "gpt-4o",
  "gpt-4o-mini",
  "claude-3-sonnet",
  "claude-3-opus",
  "claude-3-haiku",
  "gemini-1.5-pro",
  "gemini-1.5-flash",
] as const;

/** Available tools for agent creation */
const AVAILABLE_TOOLS = [
  { name: "search", value: "search", description: "Web search capability" },
  { name: "fetch_url", value: "fetch_url", description: "Fetch URL content" },
  { name: "read_file", value: "read_file", description: "Read local files" },
  { name: "search_code", value: "search_code", description: "Search codebase" },
  { name: "calculator", value: "calculator", description: "Math operations" },
] as const;

/** Agent type display names and descriptions */
const AGENT_TYPES: Record<
  AgentType | "custom",
  { name: string; description: string }
> = {
  general: {
    name: "General",
    description: "Generic conversational assistant",
  },
  researcher: {
    name: "Researcher",
    description: "Research and information synthesis",
  },
  reviewer: {
    name: "Reviewer",
    description: "Code review and analysis",
  },
  typescript: {
    name: "TypeScript",
    description: "Full TypeScript implementation",
  },
  custom: {
    name: "Custom",
    description: "Minimal template - customize everything",
  },
};

/** Kebab-case validation regex */
const KEBAB_CASE_REGEX = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

/**
 * Validate agent name is kebab-case
 */
export function validateAgentName(name: string): boolean {
  return KEBAB_CASE_REGEX.test(name);
}

/**
 * Convert kebab-case to camelCase for variable names
 */
export function kebabToCamel(str: string): string {
  return str.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
}

/**
 * Generate YAML content for an agent
 */
export function generateAgentYaml(
  name: string,
  options: {
    type: AgentType | "custom";
    model: string;
    tools?: string[];
  },
): string {
  const vars: TemplateVars = {
    name,
    model: options.model,
    agentName: kebabToCamel(name),
  };

  // Custom type uses general template with minimal config
  const templateType =
    options.type === "custom" ? "general" : (options.type as AgentType);

  // Load base template
  let content = loadAgentTemplate(templateType, vars);

  // For custom type, strip most of the template to minimal
  if (options.type === "custom") {
    content = `# Custom agent - minimal template
# Created with: Weft add agent ${name} --type custom

name: ${name}
version: "1.0.0"
type: custom

model: ${options.model}

system_prompt: |
  You are ${name}, a helpful AI assistant.
  Customize this prompt for your specific use case.

temperature: 0.7
max_tokens: 2048
`;
  }

  // Add custom tools if provided and different from template defaults
  if (options.tools && options.tools.length > 0 && options.type === "custom") {
    content += `
tools:
${options.tools.map((tool) => `  - name: ${tool}`).join("\n")}
`;
  }

  return content;
}

/**
 * Generate TypeScript content for an agent
 */
export function generateAgentTypeScript(
  name: string,
  options: {
    model: string;
    tools?: string[];
  },
): string {
  const vars: TemplateVars = {
    name,
    model: options.model,
    agentName: kebabToCamel(name),
  };

  return loadAgentTemplate("typescript", vars);
}

/**
 * Generate test file content for an agent
 */
export function generateAgentTest(name: string): string {
  const agentName = kebabToCamel(name);

  return `/**
 * Tests for ${name} agent
 * Generated by: Weft add agent ${name}
 */
import { describe, it, expect, vi, beforeEach } from "vitest";

// Mock the agent module
vi.mock("../agents/${name}", () => ({
  ${agentName}: {
    run: vi.fn(),
  },
  run: vi.fn(),
}));

describe("${name} agent", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it("should be defined", async () => {
    const { ${agentName} } = await import("../agents/${name}");
    expect(${agentName}).toBeDefined();
  });

  it("should have a run function", async () => {
    const { run } = await import("../agents/${name}");
    expect(typeof run).toBe("function");
  });

  it("should return expected response structure", async () => {
    const { run } = await import("../agents/${name}");
    const mockResult = {
      response: "Hello, I'm ${name}",
      source: "agent",
      confidence: 0.9,
    };
    vi.mocked(run).mockResolvedValueOnce(mockResult);

    const result = await run("Hello");
    expect(result).toHaveProperty("response");
    expect(result).toHaveProperty("source");
    expect(result).toHaveProperty("confidence");
  });
});
`;
}

interface AgentPromptAnswers {
  type: AgentType | "custom";
  model: string;
  tools: string[];
  createTest: boolean;
}

interface OverwriteAnswers {
  overwrite: boolean;
}

/**
 * Prompt user for agent configuration
 */
async function promptAgentConfig(): Promise<AgentPromptAnswers> {
  const answers = await inquirer.prompt<AgentPromptAnswers>([
    {
      type: "list",
      name: "type",
      message: "Select agent type:",
      choices: Object.entries(AGENT_TYPES).map(
        ([value, { name, description }]) => ({
          name: `${name} - ${description}`,
          value,
        }),
      ),
      default: "general",
    },
    {
      type: "list",
      name: "model",
      message: "Select AI model:",
      choices: AVAILABLE_MODELS.map((model) => ({ name: model, value: model })),
      default: "gpt-4o",
    },
    {
      type: "checkbox",
      name: "tools",
      message: "Select tools (optional):",
      choices: AVAILABLE_TOOLS.map((tool) => ({
        name: `${tool.name} - ${tool.description}`,
        value: tool.value,
      })),
    },
    {
      type: "confirm",
      name: "createTest",
      message: "Create test file?",
      default: true,
    },
  ]);

  return answers;
}

/**
 * Prompt for overwrite confirmation
 */
async function promptOverwrite(filePath: string): Promise<boolean> {
  const { overwrite } = await inquirer.prompt<OverwriteAnswers>([
    {
      type: "confirm",
      name: "overwrite",
      message: `File ${filePath} already exists. Overwrite?`,
      default: false,
    },
  ]);
  return overwrite;
}

/**
 * Write file with directory creation
 */
function writeFile(filePath: string, content: string): void {
  const dir = dirname(filePath);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
  writeFileSync(filePath, content, "utf-8");
}

/**
 * Create the add command with subcommands
 */
export function createAddCommand(): Command {
  const addCommand = new Command("add").description(
    "Add new components to your project",
  );

  // Weft add agent <name>
  addCommand
    .command("agent <name>")
    .description("Scaffold a new AI agent")
    .option("--yaml-only", "Only create YAML definition file")
    .option("--ts-only", "Only create TypeScript implementation file")
    .option(
      "-t, --type <type>",
      "Agent type (general, researcher, reviewer, custom)",
    )
    .option("-m, --model <model>", "AI model to use")
    .option("--no-test", "Skip test file creation")
    .action(
      async (
        name: string,
        options: {
          yamlOnly?: boolean;
          tsOnly?: boolean;
          type?: string;
          model?: string;
          test?: boolean;
        },
      ) => {
        // Validate name is kebab-case
        if (!validateAgentName(name)) {
          console.error(
            chalk.red(`Error: Agent name must be kebab-case (e.g., my-agent)`),
          );
          console.error(chalk.gray(`  Got: "${name}"`));
          console.error(
            chalk.gray(
              `  Valid examples: research-agent, code-reviewer, my-bot`,
            ),
          );
          process.exit(1);
        }

        // Determine file paths
        const cwd = process.cwd();
        const yamlPath = join(cwd, "agents", `${name}.yaml`);
        const tsPath = join(cwd, "agents", `${name}.ts`);
        const testPath = join(cwd, "tests", `${name}.test.ts`);

        // Get configuration - either from options or prompts
        let config: AgentPromptAnswers;

        if (options.type && options.model) {
          // Non-interactive mode with provided options
          config = {
            type: options.type as AgentType | "custom",
            model: options.model,
            tools: [],
            createTest: options.test !== false,
          };
        } else {
          // Interactive mode
          console.log(chalk.blue(`\nCreating agent: ${chalk.bold(name)}\n`));
          config = await promptAgentConfig();
        }

        const filesToCreate: Array<{
          path: string;
          content: string;
          type: string;
        }> = [];

        // Determine which files to create
        const createYaml = !options.tsOnly;
        const createTs = !options.yamlOnly || config.type === "typescript";
        const createTest = config.createTest && !options.yamlOnly;

        // Check for existing files and prepare content
        if (createYaml) {
          if (existsSync(yamlPath)) {
            const shouldOverwrite = await promptOverwrite(yamlPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${yamlPath}`));
            } else {
              filesToCreate.push({
                path: yamlPath,
                content: generateAgentYaml(name, config),
                type: "YAML definition",
              });
            }
          } else {
            filesToCreate.push({
              path: yamlPath,
              content: generateAgentYaml(name, config),
              type: "YAML definition",
            });
          }
        }

        if (createTs) {
          if (existsSync(tsPath)) {
            const shouldOverwrite = await promptOverwrite(tsPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${tsPath}`));
            } else {
              filesToCreate.push({
                path: tsPath,
                content: generateAgentTypeScript(name, config),
                type: "TypeScript implementation",
              });
            }
          } else {
            filesToCreate.push({
              path: tsPath,
              content: generateAgentTypeScript(name, config),
              type: "TypeScript implementation",
            });
          }
        }

        if (createTest) {
          if (existsSync(testPath)) {
            const shouldOverwrite = await promptOverwrite(testPath);
            if (!shouldOverwrite) {
              console.log(chalk.yellow(`Skipping ${testPath}`));
            } else {
              filesToCreate.push({
                path: testPath,
                content: generateAgentTest(name),
                type: "test file",
              });
            }
          } else {
            filesToCreate.push({
              path: testPath,
              content: generateAgentTest(name),
              type: "test file",
            });
          }
        }

        // Create files
        if (filesToCreate.length === 0) {
          console.log(chalk.yellow("\nNo files to create."));
          return;
        }

        const spinner = ora("Creating agent files...").start();

        try {
          for (const file of filesToCreate) {
            writeFile(file.path, file.content);
          }
          spinner.succeed("Agent files created successfully!");

          // Summary
          console.log(chalk.green("\n✓ Created files:"));
          for (const file of filesToCreate) {
            console.log(chalk.gray(`  - ${file.path} (${file.type})`));
          }

          // Next steps
          console.log(chalk.blue("\n📝 Next steps:"));
          if (createYaml) {
            console.log(
              chalk.gray(`  1. Edit ${yamlPath} to customize your agent`),
            );
          }
          if (createTs) {
            console.log(chalk.gray(`  2. Implement tools in ${tsPath}`));
          }
          console.log(chalk.gray(`  3. Run your agent with: Weft run ${name}`));
        } catch (error) {
          spinner.fail("Failed to create agent files");
          console.error(
            chalk.red(error instanceof Error ? error.message : String(error)),
          );
          process.exit(1);
        }
      },
    );

  return addCommand;
}
